import os
from pathlib import Path
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

DATA_DIR = Path(__file__).resolve().parent / "backend" / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)
PDF_PATH = DATA_DIR / "enterprise_platform_spec.pdf"

def generate_pdf():
    doc = SimpleDocTemplate(str(PDF_PATH), pagesize=letter, rightMargin=54, leftMargin=54, topMargin=54, bottomMargin=54)
    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=14
    )
    h1_style = ParagraphStyle(
        'DocH1',
        parent=styles['Heading2'],
        fontSize=15,
        leading=18,
        textColor=colors.HexColor("#0f172a"),
        spaceBefore=14,
        spaceAfter=8
    )
    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceAfter=6
    )

    story = []

    # Title
    story.append(Paragraph("Enterprise Cloud Data Platform Architecture & Specification v4.2", title_style))
    story.append(Paragraph("Confidential Technical Documentation & Runbook — Core Infrastructure Engineering", body_style))
    story.append(Spacer(1, 10))

    # Section 1
    story.append(Paragraph("## Section 1: Microservices Architecture & System Overview", h1_style))
    story.append(Paragraph(
        "The Enterprise Cloud Data Platform operates on an air-gapped, zero-cloud dependency architecture. "
        "The system decouples data ingestion, semantic vector indexing, hybrid retrieval, and generative inference into "
        "independent microservices. The ingestion subsystem utilizes IBM Docling for native layout-aware parsing of technical documents, "
        "preserving headers, tabular metadata, and code structures. Documents are segmented using recursive header chunking with "
        "a target window of 1500 characters and a 150-character overlap.",
        body_style
    ))
    story.append(Paragraph(
        "The storage layer utilizes an embedded Qdrant vector database operating in local disk persistence mode. "
        "To achieve enterprise-grade recall, Qdrant combines dense vector embeddings generated by BAAI/bge-small-en-v1.5 (384 dimensions) "
        "with sparse BM25 token frequencies, fused via Reciprocal Rank Fusion (RRF).",
        body_style
    ))
    story.append(Spacer(1, 8))

    # Section 2
    story.append(Paragraph("## Section 2: High Availability, SLA Metrics & Disaster Recovery", h1_style))
    story.append(Paragraph(
        "The platform guarantees high availability and strict service level agreements (SLAs) across all tier-1 production regions. "
        "The defined SLA commitments and recovery objectives are detailed in the operational matrix below:",
        body_style
    ))

    table_data = [
        ["Service Metric", "Target Threshold", "Measurement Interval", "Penalties / Breach Actions"],
        ["Platform Uptime SLA", "99.995% Uptime", "Monthly Rolling", "Tier-1 Credit Reallocation"],
        ["Recovery Time Objective (RTO)", "Under 15 Minutes", "Per Incident Event", "Automatic Standby Cluster Failover"],
        ["Recovery Point Objective (RPO)", "0 Seconds (RPO=0)", "Continuous Sync", "Zero Data Loss Synchronous Replication"],
        ["P99 Query Latency SLA", "Under 120 ms", "Sub-second 15,000 req/s", "Horizontal Pod Autoscaler Trigger"],
        ["Cross-Encoder Rerank Latency", "Under 85 ms", "Top-15 Candidates", "Thread Pool Concurrency Scaling"]
    ]
    t = Table(table_data, colWidths=[140, 110, 110, 140])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#2563eb")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
        ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor("#f8fafc")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 1), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    story.append(t)
    story.append(Spacer(1, 10))

    # Section 3
    story.append(Paragraph("## Section 3: Error Code Catalog & Incident Handling Runbook", h1_style))
    story.append(Paragraph(
        "Production systems must handle and log standard enterprise platform errors according to the following specifications:",
        body_style
    ))
    story.append(Paragraph(
        "<b>ERR-409-TIMEOUT</b>: Distributed lock acquisition timed out after 30,000 ms. "
        "This error is triggered when an active transaction in the distributed worker cluster fails to acquire or renew a mutex "
        "in the distributed lock coordinator due to partition lag or high contention on shared tenant state. "
        "Incident Resolution: 1. Terminate the stale transaction thread immediately to prevent cascading deadlocks. "
        "2. Inspect Redis cluster shard health and active lock keys using CLUSTER NODES. "
        "3. Trigger an idempotent rollback of uncommitted operations. "
        "4. Client applications MUST implement exponential backoff with randomized jitter between 200 ms and 5,000 ms before retying.",
        body_style
    ))
    story.append(Paragraph(
        "<b>ERR-502-BAD-GATEWAY</b>: Ingress gateway upstream connection failure. "
        "Occurs when Envoy or NGINX ingress router times out after 5,000 ms attempting to establish a TCP handshake with the upstream Auth-Worker pod. "
        "Resolution: Check Kubernetes pod readiness probes and inspect cluster coredns resolver logs.",
        body_style
    ))
    story.append(Paragraph(
        "<b>ERR-401-TOKEN-EXPIRED</b>: Bearer authentication token has exceeded its maximum validity window of 3,600 seconds. "
        "Clients must exchange their cryptographically signed refresh token at /api/v1/auth/refresh to receive a new JSON Web Token.",
        body_style
    ))
    story.append(Paragraph(
        "<b>ERR-429-RATE-LIMIT</b>: Tenant quota exceeded. The standard rate limit is 5,000 requests per minute per authenticated tenant organization. "
        "Surplus requests are queued in the token bucket or dropped with a Retry-After response header.",
        body_style
    ))
    story.append(Spacer(1, 8))

    # Section 4
    story.append(Paragraph("## Section 4: Security Compliance, Encryption & Zero-Trust Governance", h1_style))
    story.append(Paragraph(
        "The platform complies with SOC2 Type II, ISO/IEC 27001, and HIPAA compliance frameworks for healthcare and financial enterprise workloads. "
        "All data at rest stored within the embedded Qdrant vector database and attached block volumes is encrypted using AES-256-GCM. "
        "Cryptographic keys are managed via AWS KMS Customer Managed Keys (CMK) or HashiCorp Vault with automated 90-day key rotation.",
        body_style
    ))
    story.append(Paragraph(
        "All internal network communications enforce mutual TLS (mTLS) with TLS 1.3 protocol standards, eliminating unencrypted plain-text transit. "
        "Role-Based Access Control (RBAC) and attribute-based security policies restrict data access at the document chunk level. "
        "Auditing logs are immutably streamed to an append-only WORM (Write Once Read Many) compliant storage bucket.",
        body_style
    ))
    story.append(Spacer(1, 8))

    # Section 5
    story.append(Paragraph("## Section 5: Cross-Encoder Reranking & Abstention Guardrail Specifications", h1_style))
    story.append(Paragraph(
        "To eliminate LLM hallucinations and optimize context precision, the RAG engine implements a two-stage retrieval pipeline: "
        "Stage 1 performs hybrid retrieval to fetch top-15 candidate chunks using Reciprocal Rank Fusion. "
        "Stage 2 routes these candidates through a local BAAI/bge-reranker-base cross-encoder model. "
        "Raw cross-encoder output logits are normalized using a sigmoid transformation: S_norm = 1 / (1 + exp(-logit)). "
        "An Abstention Guardrail is configured with a strict confidence threshold of 0.35. "
        "If the top-ranked chunk exhibits a normalized rerank score below 0.35, the pipeline immediately abstains from generation, "
        "returning is_grounded=False and the message 'Insufficient context in the knowledge base to answer this question reliably.'",
        body_style
    ))

    doc.build(story)
    print(f"Generated enterprise PDF at {PDF_PATH} ({os.path.getsize(PDF_PATH)} bytes)")

if __name__ == "__main__":
    generate_pdf()
